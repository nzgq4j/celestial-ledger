/** Index (0–7) of the principal phase for a Sun–Moon elongation in degrees. */
export function moonPhaseIndex(angleDegrees: number) {
  return Math.floor(((((angleDegrees % 360) + 360) % 360) + 22.5) / 45) % 8;
}

export function fillCopy(
  template: string,
  values: Record<string, string | number>,
) {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
