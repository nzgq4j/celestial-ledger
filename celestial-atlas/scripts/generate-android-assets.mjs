// Generates the Android launcher icons, adaptive icon layers, splash images and
// notification icon from one SVG of the gold astrolabe mark.
// Usage: node scripts/generate-android-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const RES = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'android', 'app', 'src', 'main', 'res');
const NAVY = '#0a1128', GOLD = '#c9a35a', BRIGHT = '#e3c27e';

/** The mark on a `size` canvas, drawn with diameter `d` (both in px). */
function markSvg(size, d, { bg = null, shape = 'none', color = GOLD, core = BRIGHT } = {}) {
  const c = size / 2, r = d / 2, w = Math.max(1, d * 0.035);
  const back = !bg ? '' : shape === 'circle'
    ? `<circle cx="${c}" cy="${c}" r="${c}" fill="${bg}"/>`
    : shape === 'rounded' ? `<rect width="${size}" height="${size}" rx="${size * 0.18}" fill="${bg}"/>`
    : `<rect width="${size}" height="${size}" fill="${bg}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">${back}
  <circle cx="${c}" cy="${c}" r="${r}" fill="none" stroke="${color}" stroke-width="${w}"/>
  <circle cx="${c}" cy="${c}" r="${r * 0.72}" fill="none" stroke="${color}" stroke-width="${w * 0.8}" stroke-dasharray="${w * 2.2} ${w * 1.8}" opacity="0.75"/>
  <line x1="${c}" y1="${c - r * 1.18}" x2="${c}" y2="${c + r * 1.18}" stroke="${color}" stroke-width="${w * 0.8}" opacity="0.75"/>
  <line x1="${c - r * 1.18}" y1="${c}" x2="${c + r * 1.18}" y2="${c}" stroke="${color}" stroke-width="${w * 0.8}" opacity="0.75"/>
  <circle cx="${c}" cy="${c - r}" r="${w * 1.6}" fill="${core}"/>
  <circle cx="${c}" cy="${c}" r="${r * 0.2}" fill="${core}"/>
</svg>`;
}

const png = (svg, file) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  return sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(file);
};

const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

const jobs = [];
for (const [name, k] of Object.entries(DENSITIES)) {
  const legacy = Math.round(48 * k), fg = Math.round(108 * k);
  jobs.push(png(markSvg(legacy, legacy * 0.62, { bg: NAVY, shape: 'rounded' }), `${RES}/mipmap-${name}/ic_launcher.png`));
  jobs.push(png(markSvg(legacy, legacy * 0.62, { bg: NAVY, shape: 'circle' }), `${RES}/mipmap-${name}/ic_launcher_round.png`));
  // Adaptive foreground: keep the mark inside the 66 dp safe zone of the 108 dp layer.
  jobs.push(png(markSvg(fg, fg * 0.5), `${RES}/mipmap-${name}/ic_launcher_foreground.png`));
  jobs.push(png(markSvg(fg, fg * 0.5, { color: '#ffffff', core: '#ffffff' }), `${RES}/mipmap-${name}/ic_launcher_monochrome.png`));
}

// Splash images (pre-Android 12 and the Capacitor splash plugin): navy with a centred mark.
const SPLASH = {
  'drawable': [480, 320],
  'drawable-port-mdpi': [320, 480], 'drawable-port-hdpi': [480, 800], 'drawable-port-xhdpi': [720, 1280],
  'drawable-port-xxhdpi': [960, 1600], 'drawable-port-xxxhdpi': [1280, 1920],
  'drawable-land-mdpi': [480, 320], 'drawable-land-hdpi': [800, 480], 'drawable-land-xhdpi': [1280, 720],
  'drawable-land-xxhdpi': [1600, 960], 'drawable-land-xxxhdpi': [1920, 1280],
};
for (const [dir, [w, h]] of Object.entries(SPLASH)) {
  const d = Math.round(Math.min(w, h) * 0.28), s = Math.max(w, h);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}"><rect width="${w}" height="${h}" fill="${NAVY}"/>
    <g transform="translate(${(w - s) / 2} ${(h - s) / 2})">${markSvg(s, d).replace(/^<svg[^>]*>|<\/svg>$/g, '')}</g></svg>`;
  jobs.push(png(svg, `${RES}/${dir}/splash.png`));
}
await Promise.all(jobs);

// Vector drawables: Android 12+ splash icon and the notification small icon.
const vectorMark = (color, core, extra = '') => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-android-assets.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">${extra}
    <path android:strokeColor="${color}" android:strokeWidth="1.6" android:fillColor="#00000000"
        android:pathData="M54,32a22,22 0,1 1,0 44a22,22 0,1 1,0 -44z"/>
    <path android:strokeColor="${color}" android:strokeWidth="1.2" android:fillColor="#00000000" android:strokeAlpha="0.75"
        android:pathData="M54,38.2a15.8,15.8 0,1 1,0 31.6a15.8,15.8 0,1 1,0 -31.6z"/>
    <path android:strokeColor="${color}" android:strokeWidth="1.2" android:strokeAlpha="0.75" android:pathData="M54,28L54,80M28,54L80,54"/>
    <path android:fillColor="${core}" android:pathData="M54,49.6a4.4,4.4 0,1 1,0 8.8a4.4,4.4 0,1 1,0 -8.8z"/>
    <path android:fillColor="${core}" android:pathData="M54,29.5a2.5,2.5 0,1 1,0 5a2.5,2.5 0,1 1,0 -5z"/>
</vector>
`;
fs.writeFileSync(`${RES}/drawable/splash_mark.xml`, vectorMark(GOLD.toUpperCase(), BRIGHT.toUpperCase()));
const stat = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-android-assets.mjs. Notification icons must be white on transparent. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">
    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="1.6" android:fillColor="#00000000"
        android:pathData="M12,3.5a8.5,8.5 0,1 1,0 17a8.5,8.5 0,1 1,0 -17z"/>
    <path android:strokeColor="#FFFFFFFF" android:strokeWidth="1.2" android:pathData="M12,1L12,23M1,12L23,12"/>
    <path android:fillColor="#FFFFFFFF" android:pathData="M12,9.3a2.7,2.7 0,1 1,0 5.4a2.7,2.7 0,1 1,0 -5.4z"/>
</vector>
`;
fs.writeFileSync(`${RES}/drawable/ic_stat_atlas.xml`, stat);

// Adaptive icon definitions with a themed (monochrome) layer for Android 13+.
const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
`;
fs.writeFileSync(`${RES}/mipmap-anydpi-v26/ic_launcher.xml`, adaptive);
fs.writeFileSync(`${RES}/mipmap-anydpi-v26/ic_launcher_round.xml`, adaptive);
// The template's vector foreground (Capacitor logo) is no longer used.
fs.rmSync(`${RES}/drawable-v24/ic_launcher_foreground.xml`, { force: true });
console.log('Android icons, splash images and notification icon generated.');
